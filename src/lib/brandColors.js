// Step 1 of the chain: `{ [teamId]: [primary, secondary] }` for every affiliate
// research actually resolved. An entry marked `"found": false` carries no
// `pair` and so gets no key here — three do today (482 Corpus Christi, 553
// Knoxville, 1956 Somerset: recent rebrands where only colour NAMES were
// found, never a hex). They fall through to step 2 rather than wearing an
// invented colour, and the lab flags them (milbHasResearchedColor below).
export const MILB_RESEARCHED_PAIRS = byTeam(MILB_COLORS, (e) => e.pair)

// Step 3, the last resort: the same neutral graphite pair wpaBandColors.js's
// chipColorsFor falls back to for an unrecognized team — reused rather than
// inventing a second "unknown team" colour. Only reachable for a team id that
// is in NEITHER table: not a researched affiliate, and with no parent org
// (a complex/rookie-league or otherwise unaffiliated club).
export const NEUTRAL_FALLBACK_PAIR = ['#6B6558', '#938C7C']

// Steps 1-2 only: `teamId`'s real brand pair — its own if research resolved
// one, else its parent MLB org's — or null when neither exists. The null rung
// is what callers whose contract is "no known colour, render something else
// entirely" read (teams.js's teamTintColor, teamStripeGradient, teamChipColors);
// callers that must paint SOMETHING read milbColorPair below instead. One
// ordering, two endings — not two chains.
export function milbBrandPair(teamId) {
  return MILB_RESEARCHED_PAIRS[teamId] ?? TEAM_COLOR_PAIRS[MILB_PARENT_ORG[teamId]] ?? null
}

// The full chain, steps 1-3 — for every surface that has to render a colour no
// matter what (the MiLB logo tile, the WPA band, the lab's own preview).
export function milbColorPair(teamId) {
  return milbBrandPair(teamId) ?? NEUTRAL_FALLBACK_PAIR
}

// Whether `teamId` has a real researched colour OF ITS OWN — deliberately NOT
// "the chain found something", so the lab still flags an affiliate that is only
// borrowing its parent org's pair, and the three `found: false` clubs stay
// visibly unresolved instead of looking indistinguishable from a
// confidently-researched one.
export function milbHasResearchedColor(teamId) {
  return Boolean(MILB_RESEARCHED_PAIRS[teamId])
}
