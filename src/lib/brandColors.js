//
// It sits below both on purpose. milbColors.js already reaches teams.js
// transitively (via wpaLogo.js), so putting the chain in either of them and
// importing the other would close an import cycle. Everything here is a leaf:
// two static tables and pure functions over them. See src/lib/CLAUDE.md.
//
// The chain, in one place, read by every MiLB surface:
//
//   1. the affiliate's own researched pair   (data/milb-colors.json)
//   2. its parent MLB org's pair             (via MILB_PARENT_ORG)
//   3. NEUTRAL_FALLBACK_PAIR                 (milbColorPair only)
//
// Step 1 is what changed in July 2026. Before it, the headshot tint jumped
// straight to step 2 and never saw the affiliate at all — a Durham Bulls
// headshot tinted RAYS navy — while the logo tile read step 1 and had no step 2,
// so the two disagreed by construction. There is now one ordering, and both
// teams.js's teamTintColor and milbColors.js's milbTreatmentTile read it.

