// List the event cards in a stacked half: node events.mjs <route> <pk> <rev>
import { createRequire } from 'node:module'
const { chromium } = createRequire(import.meta.url)('playwright')
const [route, pk, rev] = process.argv.slice(2)
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' })
const ctx = await b.newContext({ viewport: { width: 390, height: 844 } })
await ctx.addInitScript(([pk, rev]) => { if (sessionStorage.getItem('s')) return; sessionStorage.setItem('s', 1); localStorage.setItem('bbsbh:reveal:' + pk, rev); localStorage.removeItem('bbsbh:reveal-atbat:' + pk) }, [pk, rev])
const page = await ctx.newPage()
await page.route(/^https:\/\//, async (r) => { try { const res = await fetch(r.request().url()); const body = Buffer.from(await res.arrayBuffer()); await r.fulfill({ status: res.status, headers: { 'content-type': res.headers.get('content-type') ?? 'application/octet-stream', 'access-control-allow-origin': '*' }, body }) } catch { await r.abort() } })
await page.goto('http://localhost:5173' + route + '?nointro', { waitUntil: 'networkidle', timeout: 90000 }).catch(() => {})
await page.waitForTimeout(2500)
await page.locator('.trailstrip__summarybtn').click({ timeout: 5000 }).catch(() => console.log('no summary btn'))
await page.waitForTimeout(1500)
const rows = await page.evaluate(() => [...document.querySelectorAll('.pbp__entry > *, .prepitch, .prepitch > *, .notice--event, .pbp__note')].map((e) => [e.className.split(' ').slice(0, 2).join('.'), e.innerText.replace(/\s+/g, ' ').slice(0, 70)]))
rows.forEach((r, i) => console.log(i, r[0], '|', r[1]))
await b.close()
