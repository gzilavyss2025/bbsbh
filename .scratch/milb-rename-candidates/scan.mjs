// Hand-run: node .scratch/milb-rename-candidates/scan.mjs [firstSeason]
// Lists every full-season MiLB club id (sportIds 11-14) whose NAME changed
// between firstSeason and today, per statsapi's season-scoped club list
// (GET /api/v1/teams?sportId=&season=). Writes candidates.md beside this file.
// Candidates only: years come from the feed and are not source-checked. An era
// is filed under the club's CURRENT id (the Eras tab at /identity-lab).
import { readFile, writeFile } from 'node:fs/promises'

const FIRST = Number(process.argv[2] ?? 1985)
const LAST = new Date().getFullYear()
const LEVELS = { 11: 'AAA', 12: 'AA', 13: 'High-A', 14: 'A' }
const here = new URL('.', import.meta.url)
const filed = JSON.parse(await readFile(new URL('../../src/lib/data/season-marks.json', import.meta.url))).clubs

async function teams(sportId, season) {
  for (let i = 0; i < 3; i++) {
    try {
      const res = await fetch(`https://statsapi.mlb.com/api/v1/teams?sportId=${sportId}&season=${season}`)
      if (res.ok) return (await res.json()).teams ?? []
    } catch {}
    await new Promise((r) => setTimeout(r, 500 * (i + 1)))
  }
  console.error(`gave up on ${sportId} ${season}`)
  return []
}

const byId = new Map() // id -> { years: Map(season -> {name, level}) }
const jobs = []
for (let y = FIRST; y <= LAST; y++) for (const sp of Object.keys(LEVELS)) jobs.push([Number(sp), y])
for (let i = 0; i < jobs.length; i += 8) {
  await Promise.all(
    jobs.slice(i, i + 8).map(async ([sp, y]) => {
      for (const t of await teams(sp, y)) {
        if (!byId.has(t.id)) byId.set(t.id, new Map())
        byId.get(t.id).set(y, { name: t.name, level: LEVELS[sp] })
      }
    }),
  )
}

const rows = []
for (const [id, seasons] of byId) {
  const years = [...seasons.keys()].sort((a, b) => a - b)
  const eras = []
  for (const y of years) {
    const { name, level } = seasons.get(y)
    const last = eras.at(-1)
    if (last && last.name === name && last.to === y - 1) last.to = y
    else eras.push({ name, from: y, to: y, level })
  }
  const names = new Set(eras.map((e) => e.name))
  if (names.size < 2) continue
  rows.push({ id, current: eras.at(-1), eras })
}
rows.sort((a, b) => a.current.name.localeCompare(b.current.name))

const lines = [
  `# MiLB name changes ${FIRST}-${LAST} (candidates)`,
  '',
  `Generated by scan.mjs from statsapi's season-scoped club lists. ${rows.length} club ids changed name. Years come from the feed and are NOT source-checked; the logo to find is every era above the last one in each row (the last is today's name). File each under the CURRENT id in /identity-lab, Eras tab. "Filed" means season-marks.json already has an era for that id.`,
  '',
  '| Current club (id) | Level | Old names to find (seasons) | Filed |',
  '|---|---|---|---|',
]
for (const r of rows) {
  const old = r.eras.slice(0, -1).map((e) => `${e.name} (${e.from}–${e.to})`).join('; ')
  lines.push(`| ${r.current.name} (${r.id}) | ${r.current.level} | ${old} | ${filed[r.id] ? 'yes' : ''} |`)
}
await writeFile(new URL('candidates.md', here), lines.join('\n') + '\n')
console.log(rows.length, 'clubs with name changes')
